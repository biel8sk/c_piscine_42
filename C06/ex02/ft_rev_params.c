#include <unistd.h>

int	main(int argc, char **argv)
{
	int		i;
	char	*p;

	i = argc -1;
	while (argc)
	{
		if (i > 0)
		{
			p = argv[i];
			while (*p != '\0')
			{
				write(1, p, 1);
				p++;
			}
			write(1, "\n", 1);
		}
		i--;
		argc--;
	}
}
